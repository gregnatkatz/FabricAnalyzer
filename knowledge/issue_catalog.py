# Build and cache the catalog
ISSUE_CATALOG = _build_catalog()

def get_all_issues():
    """Return full 500-issue catalog."""
    return ISSUE_CATALOG

def get_issues_by_category(category):
    """Return issues for a specific category."""
    return [i for i in ISSUE_CATALOG if i['category'] == category]

def get_issue_by_id(issue_id):
    """Return single issue by ID."""
    return next((i for i in ISSUE_CATALOG if i['id'] == issue_id), None)

def get_chromadb_chunks():
    """Convert issues to ChromaDB-ready chunks for embedding."""
    import hashlib
    chunks = []
    for issue in ISSUE_CATALOG:
        chunk_id = hashlib.md5(issue['id'].encode()).hexdigest()[:12]
        chunks.append({
            'id': f'issue_{chunk_id}',
            'title': f"[{issue['category']}] {issue['title']}",
            'topic': issue['category'].lower(),
            'content': (
                f"Issue: {issue['title']}\n"
                f"Category: {issue['category']}\n"
                f"Severity: {issue['severity']}\n"
                f"Description: {issue['description']}\n"
                f"Estimated Impact: {issue['impact_ms']}ms\n"
                f"Recommended Fix: {issue['fix']}\n"
                f"Detection: {issue['detection_hint']}"
            ),
        })
    return chunks

def get_category_summary():
    """Return summary of issues per category."""
    from collections import Counter
    cats = Counter(i['category'] for i in ISSUE_CATALOG)
    return dict(cats)


